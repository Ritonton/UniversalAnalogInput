/// Returns the maximum total column span across all rows (used to compute window width).
pub fn max_row_span() -> u16 {
    rows()
        .iter()
        .map(|r| r.iter().map(|&(_, _, s, _)| s).sum::<u16>())
        .max()
        .unwrap_or(22)
}
